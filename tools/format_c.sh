#!/usr/bin/env bash
# Formats the project's own C code with clang-format and the Flipper firmware's .clang-format
# (copied unchanged from flipperdevices/flipperzero-firmware at 1.5.1, the official SDK pin).
#
#   tools/format_c.sh           # format in place
#   tools/format_c.sh --check   # change nothing; fail if a file is not formatted (the gate)
#
# Runs inside the pinned espressif/idf container (see tools/check.ps1), or on any Linux box.
# clang-format is the pinned PyPI build (LLVM's own binaries), installed into
# .cache/clang-format/<version> on first use; CLANG_FORMAT names another binary of the same
# version instead (CI).
#
# Not formatted: code that is not ours or not written by hand: the vendored libssh, the
# flipper-app/lib/proto/ copy (tools/sync_proto.py makes it from proto/), and the font tables
# generated by tools/flipper/font_metrics.py.
set -euo pipefail
cd "$(dirname "$0")/.."
VERSION=18.1.8

mode=-i done=formatted
case "${1:-}" in
"") ;;
--check) mode="--dry-run --Werror" done=checked ;;
*) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

cf=${CLANG_FORMAT:-}
if [ -z "$cf" ]; then
    dir=.cache/clang-format/$VERSION
    cf=$dir/clang_format/data/bin/clang-format
    if [ ! -x "$cf" ]; then
        echo "-- installing clang-format $VERSION into $dir"
        python3 -m pip install -q --disable-pip-version-check --cache-dir .cache/pip \
            --target "$dir" "clang-format==$VERSION"
    fi
fi
have=$("$cf" --version)
case "$have" in
*"version $VERSION"*) ;;
*) echo "clang-format $VERSION needed, found: $have" >&2; exit 1 ;;
esac

mapfile -t files < <(git -c safe.directory='*' ls-files -- \
    'proto/*.[ch]' 'flipper-app/*.[ch]' 'firmware-esp32/*.[ch]' |
    grep -v -e '^flipper-app/lib/proto/' -e '^firmware-esp32/components/libssh/' \
        -e '^flipper-app/core/fontw_table\.h$' -e '^flipper-app/tests/fake_gui/font_metrics\.h$')
# shellcheck disable=SC2086 # $mode is one or two flags
"$cf" --style=file $mode "${files[@]}"
echo "clang-format $VERSION: ${#files[@]} files $done"
