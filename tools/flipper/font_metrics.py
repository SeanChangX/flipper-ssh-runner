"""Extract glyph metrics of the Flipper's GUI fonts from a firmware ELF (uFBT SDK).

Writes flipper-app/tests/fake_gui/font_metrics.h: for each printable ASCII glyph its
advance, u8g2 box width and x offset (string widths) and the box of its inked pixels
(the bitmaps are decoded for that, not kept), plus the font's ascent, descent and line
height. Only metrics are
kept (no glyph bitmaps), enough for the host render test to measure strings exactly as
u8g2_GetStrWidth does.

    python -m tools.flipper.font_metrics [path/to/firmware.elf]

SPDX-License-Identifier: GPL-3.0-only
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_ELF = ROOT / ".cache" / "ufbt" / "windows" / "unleashed" / "current" / "firmware.elf"
OUT = ROOT / "flipper-app" / "tests" / "fake_gui" / "font_metrics.h"
APP_OUT = ROOT / "flipper-app" / "core" / "fontw_table.h"

# canvas.c: FontPrimary, FontSecondary, FontKeyboard, FontBigNumbers
FONTS = [
    ("primary", "u8g2_font_helvB08_tr"),
    ("secondary", "u8g2_font_haxrcorp4089_tr"),
    ("keyboard", "u8g2_font_profont11_mr"),
    ("bignumbers", "u8g2_font_profont22_tn"),
]


def elf_symbols(data: bytes) -> tuple[dict, list]:
    assert data[:4] == b"\x7fELF" and data[4] == 1 and data[5] == 1, "ELF32 LE expected"
    shoff, = struct.unpack_from("<I", data, 0x20)
    shentsize, shnum = struct.unpack_from("<HH", data, 0x2E)
    secs = [struct.unpack_from("<IIIIIIIIII", data, shoff + i * shentsize) for i in range(shnum)]
    syms = {}
    for s in secs:
        if s[1] != 2:  # SHT_SYMTAB
            continue
        strtab = secs[s[6]]
        for off in range(s[4], s[4] + s[5], 16):
            name, value, size, _info, _other, _shndx = struct.unpack_from("<IIIBBH", data, off)
            n = data[strtab[4] + name: data.index(b"\0", strtab[4] + name)].decode()
            syms[n] = (value, size)
    return syms, secs


def read_at(data: bytes, secs: list, addr: int, size: int) -> bytes:
    for s in secs:
        if s[1] == 1 and s[3] <= addr < s[3] + s[5]:  # SHT_PROGBITS by address
            o = s[4] + addr - s[3]
            return data[o:o + size]
    raise KeyError(hex(addr))


class Bits:
    def __init__(self, b: bytes, pos: int):
        self.b, self.byte, self.bit = b, pos, 0

    def u(self, n: int) -> int:
        v = 0
        for i in range(n):
            v |= ((self.b[self.byte] >> self.bit) & 1) << i
            self.bit += 1
            if self.bit == 8:
                self.bit, self.byte = 0, self.byte + 1
        return v

    def s(self, n: int) -> int:
        return self.u(n) - (1 << (n - 1))


def ink_box(r: Bits, w: int, h: int, b0: int, b1: int):
    """Decode the glyph's run-length bitmap (u8g2_font_decode_glyph) only to find the rows
    and columns that have ink; returns (x0, y0, x1, y1) inside the w x h box, or None."""
    x = y = 0
    x0 = y0 = 1 << 10
    x1 = y1 = -1

    def run(n: int, ink: bool) -> None:
        nonlocal x, y, x0, y0, x1, y1
        for _ in range(n):
            if ink and y < h:
                x0, y0, x1, y1 = min(x0, x), min(y0, y), max(x1, x), max(y1, y)
            x += 1
            if x >= w:
                x, y = 0, y + 1

    if not w or not h:
        return None
    while y < h:
        a, b = r.u(b0), r.u(b1)
        while True:
            run(a, False)
            run(b, True)
            if not r.u(1):
                break
    return None if x1 < 0 else (x0, y0, x1, y1)


def parse_font(f: bytes) -> dict:
    h = f[:23]
    b0, b1 = h[2], h[3]
    bw, bh, bx, by, bdx = h[4], h[5], h[6], h[7], h[8]
    glyphs = {}
    p = 23
    while p < len(f):
        enc, jump = f[p], f[p + 1]
        if jump == 0:
            break
        r = Bits(f, p + 2)
        w, hh, x, y, dx = r.u(bw), r.u(bh), r.s(bx), r.s(by), r.s(bdx)
        box = ink_box(r, w, hh, b0, b1)
        if box:  # ink relative to the pen and baseline: left, top row above it, size
            ix0, iy0, ix1, iy1 = box
            ink = (x + ix0, hh + y - iy0, ix1 - ix0 + 1, iy1 - iy0 + 1)
        else:
            ink = (0, 0, 0, 0)
        glyphs[enc] = (w, x, dx) + ink
        p += jump
    sb = lambda v: v - 256 if v > 127 else v
    return {"ascent": sb(h[13]), "descent": sb(h[14]), "max_h": h[10], "glyphs": glyphs}


def main() -> int:
    elf = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_ELF
    data = elf.read_bytes()
    syms, secs = elf_symbols(data)
    out = [
        "/* Generated by tools/flipper/font_metrics.py from the firmware ELF; do not edit.",
        " * Glyph metrics and ink boxes only (no bitmaps). SPDX-License-Identifier: GPL-3.0-only */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint8_t present, w; /* u8g2 box width */",
        "    int8_t x, dx; /* u8g2 box x offset, advance */",
        "    int8_t ink_x, ink_top; /* inked pixels: left from the pen, top row above the baseline */",
        "    uint8_t ink_w, ink_h;",
        "} FakeGlyph;",
        "typedef struct { int8_t ascent, descent, max_h; FakeGlyph g[95]; } FakeFont; /* ' '..'~' */",
        "",
    ]
    for key, sym in FONTS:
        addr, size = syms[sym]
        font = parse_font(read_at(data, secs, addr, size))
        rows = []
        for c in range(32, 127):
            g = font["glyphs"].get(c)
            rows.append("{0}" if g is None else "{1," + ",".join(str(v) for v in g) + "}")
        out.append(f"static const FakeFont fake_font_{key} = {{{font['ascent']}, {font['descent']}, {font['max_h']}, {{")
        for i in range(0, 95, 8):
            out.append("    " + ", ".join(rows[i:i + 8]) + ",")
        out.append("}};")
        out.append("")
        if key == "secondary":
            secondary = font
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")

    # The app measures FontSecondary strings without a canvas (labels the stock modules
    # would otherwise cut): advances, and the last glyph's box width + x offset.
    adv, last = [], []
    for c in range(32, 127):
        g = secondary["glyphs"].get(c)
        adv.append(str(g[2] if g else 0))
        last.append(str(g[0] + g[1] if g else 0))
    app = [
        "/* Generated by tools/flipper/font_metrics.py from the firmware ELF; do not edit.",
        " * FontSecondary (u8g2 haxrcorp4089) widths for ' '..'~'. SPDX-License-Identifier: GPL-3.0-only */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "static const uint8_t fontw_secondary_adv[95] = {" + ", ".join(adv) + "};",
        "static const uint8_t fontw_secondary_last[95] = {" + ", ".join(last) + "};",
        "",
    ]
    APP_OUT.write_text("\n".join(app), encoding="utf-8", newline="\n")
    print(f"wrote {APP_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
