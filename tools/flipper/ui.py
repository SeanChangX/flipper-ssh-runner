def template(name: str) -> Template:
    width, rows = TEMPLATES[name]
    return Template(name, rows, width)


@dataclass(frozen=True)
class Hit:
    x: int
    y: int
    selected: bool  # drawn inverted: the menu's cursor is on it


def find_px(px: list[list[int]], t: Template) -> Hit | None:
    rows = _rows(px)
    mask = (1 << t.width) - 1
    h = len(t.rows)
    for y in range(H - h + 1):
        for x in range(W - t.width + 1):
            got = [(rows[y + i] >> x) & mask for i in range(h)]
            if got == list(t.rows):
                return Hit(x, y, False)
            if all(g == (~r & mask) for g, r in zip(got, t.rows)):
                return Hit(x, y, True)
    return None


def find(frame: bytes, name: str) -> Hit | None:
    """Where the label `name` is on the frame (and whether it is selected), or None."""
    return find_px(screen.pixels(frame), template(name))


def on_security(frame: bytes) -> bool:
    """True on Settings > Security, the screen whose right button leads to Protect (a
    permanent eFuse burn on a real board)."""
    hit = find(frame, "Security screen")
    return hit is not None and hit.y < 4 and not hit.selected


def main() -> int:
    """Print TEMPLATES, cut again from the committed screenshots (REFS)."""
    print("TEMPLATES: dict[str, tuple[int, tuple[int, ...]]] = {")
    for name in REFS:
        t = cut_ref(name)
        print(f"    {name!r}: ({t.width}, ({', '.join(hex(r) for r in t.rows)},)),")
    print("}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
